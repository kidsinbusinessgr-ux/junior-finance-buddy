// A slide's text: each line on its own; lines that start with "1)", "2)", …
// become a numbered list, one point under the other.
function SlideBody({ text }: { text: string }) {
  const lines = text.split("\n").map((l) => l.trim()).filter(Boolean);
  return (
    <div className="mt-4 space-y-3 text-lg leading-relaxed text-muted-foreground">
      {lines.map((line, i) => {
        const m = line.match(/^(\d{1,2}|[Α-Ω])\) (.*)$/);
        const box = line.match(/^(Παράδειγμα|Τύπος):\s*(.*)$/);
        if (box) {
          return (
            <p key={i} className="rounded-xl bg-primary/5 px-4 py-2 text-foreground">
              <b className="text-primary">{box[1]}:</b> {box[2]}
            </p>
          );
        }
        if (!m) return <p key={i}>{line}</p>;
        const [label, ...rest] = m[2].split(": ");
        return (
          <div key={i} className="flex gap-3">
            <span className="mt-0.5 grid h-7 w-7 shrink-0 place-items-center rounded-full bg-primary/10 text-sm font-black text-primary">{m[1]}</span>
            <p>
              {rest.length ? (
                <>
                  <b className="text-foreground">{label}:</b> {rest.join(": ")}
                </>
              ) : (
                m[2]
              )}
            </p>
          </div>
        );
      })}
    </div>
  );
}

