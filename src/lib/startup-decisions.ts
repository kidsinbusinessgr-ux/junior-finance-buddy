// A small stable hash, so a startup gets the same card all day.
function hash(text: string): number {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

// Today's card for a startup: not one of its recent cards, and only cards that
// fit its size. The same startup gets the same card for the whole day.
export function pickDailyCard(
  startupId: string,
  day: string,
  customers: number,
  recentCardIds: string[],
): DecisionCard {
  // A company without customers first has to find some.
  if (customers === 0 && !recentCardIds.includes("first-customers")) {
    return DECISION_CARDS.find((c) => c.id === "first-customers")!;
  }
  const fits = DECISION_CARDS.filter((c) => (c.minCustomers ?? 0) <= customers);
  const fresh = fits.filter((c) => !recentCardIds.includes(c.id));
  const pool = fresh.length ? fresh : fits;
  return pool[hash(`${startupId}:${day}`) % pool.length]!;
}
